-- -------------------------------------------------------------
-- 1. CRIACAO DAS TABELAS
-- -------------------------------------------------------------

-- Subprefeituras da cidade (ex.: Se, Mooca)
CREATE TABLE GS_SUBPREFEITURA (
    ID_SUBPREFEITURA  NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
    NM_SUBPREFEITURA  VARCHAR2(60)  NOT NULL,
    CONSTRAINT PK_GS_SUBPREFEITURA PRIMARY KEY (ID_SUBPREFEITURA),
    CONSTRAINT UK_GS_SUBPREF_NOME  UNIQUE (NM_SUBPREFEITURA)
);

-- Distritos (bairros oficiais), cada um pertence a uma subprefeitura
CREATE TABLE GS_DISTRITO (
    ID_DISTRITO       NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
    ID_SUBPREFEITURA  NUMBER(10)    NOT NULL,
    NM_DISTRITO       VARCHAR2(60)  NOT NULL,
    CONSTRAINT PK_GS_DISTRITO      PRIMARY KEY (ID_DISTRITO),
    CONSTRAINT UK_GS_DISTRITO_NOME UNIQUE (NM_DISTRITO)
);

-- Tipos de problema (ex.: tapa-buraco, entulho, bueiro)
--   NR_PRAZO_DIAS      prazo esperado de atendimento
--   NR_PESO_GRAVIDADE  1 (leve) a 5 (grave), usado no calculo de prioridade
--   NR_HORAS_ESTIMADAS horas de trabalho da equipe para resolver
CREATE TABLE GS_CATEGORIA (
    ID_CATEGORIA        NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY,
    NM_CATEGORIA        VARCHAR2(80)   NOT NULL,
    DS_CATEGORIA        VARCHAR2(255),
    NR_PRAZO_DIAS       NUMBER(3)      NOT NULL,
    NR_PESO_GRAVIDADE   NUMBER(1)      NOT NULL,
    NR_HORAS_ESTIMADAS  NUMBER(3)      NOT NULL,
    CONSTRAINT PK_GS_CATEGORIA       PRIMARY KEY (ID_CATEGORIA),
    CONSTRAINT UK_GS_CATEGORIA_NOME  UNIQUE (NM_CATEGORIA),
    CONSTRAINT CK_GS_CATEGORIA_PRAZO CHECK (NR_PRAZO_DIAS > 0),
    CONSTRAINT CK_GS_CATEGORIA_PESO  CHECK (NR_PESO_GRAVIDADE BETWEEN 1 AND 5),
    CONSTRAINT CK_GS_CATEGORIA_HORAS CHECK (NR_HORAS_ESTIMADAS > 0)
);

-- Cidadao que registra e apoia ocorrencias (dados simulados)
--   FL_PRIORITARIO  'S' para idoso ou pessoa com deficiencia
CREATE TABLE GS_CIDADAO (
    ID_CIDADAO      NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY,
    NM_CIDADAO      VARCHAR2(100)  NOT NULL,
    DS_EMAIL        VARCHAR2(120)  NOT NULL,
    NR_TELEFONE     VARCHAR2(20),
    FL_PRIORITARIO  CHAR(1)        DEFAULT 'N' NOT NULL,
    DT_CADASTRO     DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_GS_CIDADAO       PRIMARY KEY (ID_CIDADAO),
    CONSTRAINT UK_GS_CIDADAO_EMAIL UNIQUE (DS_EMAIL),
    CONSTRAINT CK_GS_CIDADAO_PRIOR CHECK (FL_PRIORITARIO IN ('S', 'N'))
);

-- Locais que aumentam a prioridade de uma ocorrencia proxima
CREATE TABLE GS_PONTO_SENSIVEL (
    ID_PONTO_SENSIVEL  NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY,
    ID_DISTRITO        NUMBER(10)     NOT NULL,
    NM_PONTO           VARCHAR2(100)  NOT NULL,
    TP_PONTO           VARCHAR2(20)   NOT NULL,
    NR_LATITUDE        NUMBER(10,7)   NOT NULL,
    NR_LONGITUDE       NUMBER(10,7)   NOT NULL,
    CONSTRAINT PK_GS_PONTO_SENSIVEL PRIMARY KEY (ID_PONTO_SENSIVEL),
    CONSTRAINT CK_GS_PONTO_TIPO     CHECK (TP_PONTO IN ('ESCOLA', 'CRECHE', 'UBS', 'HOSPITAL', 'ILPI', 'TERMINAL')),
    CONSTRAINT CK_GS_PONTO_LAT      CHECK (NR_LATITUDE BETWEEN -90 AND 90),
    CONSTRAINT CK_GS_PONTO_LON      CHECK (NR_LONGITUDE BETWEEN -180 AND 180)
);

-- Equipe de campo da subprefeitura
--   NR_HORAS_DIA          horas de trabalho disponiveis por dia
--   NR_LATITUDE/LONGITUDE ponto de saida da equipe (base)
CREATE TABLE GS_EQUIPE (
    ID_EQUIPE         NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
    ID_SUBPREFEITURA  NUMBER(10)    NOT NULL,
    NM_EQUIPE         VARCHAR2(60)  NOT NULL,
    NR_HORAS_DIA      NUMBER(2)     NOT NULL,
    NR_LATITUDE       NUMBER(10,7)  NOT NULL,
    NR_LONGITUDE      NUMBER(10,7)  NOT NULL,
    FL_ATIVA          CHAR(1)       DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_GS_EQUIPE       PRIMARY KEY (ID_EQUIPE),
    CONSTRAINT UK_GS_EQUIPE_NOME  UNIQUE (NM_EQUIPE),
    CONSTRAINT CK_GS_EQUIPE_HORAS CHECK (NR_HORAS_DIA BETWEEN 1 AND 24),
    CONSTRAINT CK_GS_EQUIPE_ATIVA CHECK (FL_ATIVA IN ('S', 'N'))
);

-- Problema registrado pelo cidadao
--   NR_PRIORIDADE  calculada pela aplicacao (gravidade, apoios, pontos sensiveis)
CREATE TABLE GS_OCORRENCIA (
    ID_OCORRENCIA   NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY,
    ID_CIDADAO      NUMBER(10)     NOT NULL,
    ID_CATEGORIA    NUMBER(10)     NOT NULL,
    ID_DISTRITO     NUMBER(10)     NOT NULL,
    DS_OCORRENCIA   VARCHAR2(500)  NOT NULL,
    DS_LOGRADOURO   VARCHAR2(120)  NOT NULL,
    NR_ENDERECO     VARCHAR2(10),
    NR_LATITUDE     NUMBER(10,7)   NOT NULL,
    NR_LONGITUDE    NUMBER(10,7)   NOT NULL,
    ST_OCORRENCIA   VARCHAR2(15)   DEFAULT 'ABERTA' NOT NULL,
    NR_PRIORIDADE   NUMBER(6,2)    DEFAULT 0 NOT NULL,
    DT_ABERTURA     DATE           DEFAULT SYSDATE NOT NULL,
    DT_RESOLUCAO    DATE,
    CONSTRAINT PK_GS_OCORRENCIA       PRIMARY KEY (ID_OCORRENCIA),
    CONSTRAINT CK_GS_OCORRENCIA_ST    CHECK (ST_OCORRENCIA IN ('ABERTA', 'EM_ANDAMENTO', 'RESOLVIDA', 'CANCELADA')),
    CONSTRAINT CK_GS_OCORRENCIA_PRIOR CHECK (NR_PRIORIDADE >= 0),
    CONSTRAINT CK_GS_OCORRENCIA_LAT   CHECK (NR_LATITUDE BETWEEN -90 AND 90),
    CONSTRAINT CK_GS_OCORRENCIA_LON   CHECK (NR_LONGITUDE BETWEEN -180 AND 180),
    CONSTRAINT CK_GS_OCORRENCIA_DATAS CHECK (DT_RESOLUCAO IS NULL OR DT_RESOLUCAO >= DT_ABERTURA)
);

-- "Tambem me afeta": um cidadao apoia uma ocorrencia uma unica vez
CREATE TABLE GS_APOIO (
    ID_APOIO       NUMBER(10)  GENERATED BY DEFAULT AS IDENTITY,
    ID_OCORRENCIA  NUMBER(10)  NOT NULL,
    ID_CIDADAO     NUMBER(10)  NOT NULL,
    DT_APOIO       DATE        DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_GS_APOIO           PRIMARY KEY (ID_APOIO),
    CONSTRAINT UK_GS_APOIO_OCORR_CID UNIQUE (ID_OCORRENCIA, ID_CIDADAO)
);

-- Visita de uma equipe para resolver uma ocorrencia
CREATE TABLE GS_ATENDIMENTO (
    ID_ATENDIMENTO  NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY,
    ID_OCORRENCIA   NUMBER(10)     NOT NULL,
    ID_EQUIPE       NUMBER(10)     NOT NULL,
    DT_AGENDADA     DATE           NOT NULL,
    DT_EXECUCAO     DATE,
    ST_ATENDIMENTO  VARCHAR2(15)   DEFAULT 'AGENDADO' NOT NULL,
    DS_OBSERVACAO   VARCHAR2(500),
    CONSTRAINT PK_GS_ATENDIMENTO     PRIMARY KEY (ID_ATENDIMENTO),
    CONSTRAINT CK_GS_ATENDIMENTO_ST  CHECK (ST_ATENDIMENTO IN ('AGENDADO', 'CONCLUIDO', 'CANCELADO')),
    CONSTRAINT CK_GS_ATENDIMENTO_EXE CHECK (DT_EXECUCAO IS NULL OR DT_EXECUCAO >= DT_AGENDADA)
);


-- -------------------------------------------------------------
-- 2. CHAVES ESTRANGEIRAS (relacionamentos)
-- -------------------------------------------------------------

-- Subprefeitura 1 : N Distrito
ALTER TABLE GS_DISTRITO ADD CONSTRAINT FK_GS_DISTRITO_SUBPREF
    FOREIGN KEY (ID_SUBPREFEITURA) REFERENCES GS_SUBPREFEITURA (ID_SUBPREFEITURA);

-- Distrito 1 : N Ponto sensivel
ALTER TABLE GS_PONTO_SENSIVEL ADD CONSTRAINT FK_GS_PONTO_DISTRITO
    FOREIGN KEY (ID_DISTRITO) REFERENCES GS_DISTRITO (ID_DISTRITO);

-- Subprefeitura 1 : N Equipe
ALTER TABLE GS_EQUIPE ADD CONSTRAINT FK_GS_EQUIPE_SUBPREF
    FOREIGN KEY (ID_SUBPREFEITURA) REFERENCES GS_SUBPREFEITURA (ID_SUBPREFEITURA);

-- Cidadao 1 : N Ocorrencia
ALTER TABLE GS_OCORRENCIA ADD CONSTRAINT FK_GS_OCORRENCIA_CIDADAO
    FOREIGN KEY (ID_CIDADAO) REFERENCES GS_CIDADAO (ID_CIDADAO);

-- Categoria 1 : N Ocorrencia
ALTER TABLE GS_OCORRENCIA ADD CONSTRAINT FK_GS_OCORRENCIA_CATEGORIA
    FOREIGN KEY (ID_CATEGORIA) REFERENCES GS_CATEGORIA (ID_CATEGORIA);

-- Distrito 1 : N Ocorrencia
ALTER TABLE GS_OCORRENCIA ADD CONSTRAINT FK_GS_OCORRENCIA_DISTRITO
    FOREIGN KEY (ID_DISTRITO) REFERENCES GS_DISTRITO (ID_DISTRITO);

-- Ocorrencia 1 : N Apoio  (apagar a ocorrencia apaga os apoios)
ALTER TABLE GS_APOIO ADD CONSTRAINT FK_GS_APOIO_OCORRENCIA
    FOREIGN KEY (ID_OCORRENCIA) REFERENCES GS_OCORRENCIA (ID_OCORRENCIA) ON DELETE CASCADE;

-- Cidadao 1 : N Apoio
ALTER TABLE GS_APOIO ADD CONSTRAINT FK_GS_APOIO_CIDADAO
    FOREIGN KEY (ID_CIDADAO) REFERENCES GS_CIDADAO (ID_CIDADAO);

-- Ocorrencia 1 : N Atendimento  (apagar a ocorrencia apaga os atendimentos)
ALTER TABLE GS_ATENDIMENTO ADD CONSTRAINT FK_GS_ATENDIMENTO_OCORRENCIA
    FOREIGN KEY (ID_OCORRENCIA) REFERENCES GS_OCORRENCIA (ID_OCORRENCIA) ON DELETE CASCADE;

-- Equipe 1 : N Atendimento
ALTER TABLE GS_ATENDIMENTO ADD CONSTRAINT FK_GS_ATENDIMENTO_EQUIPE
    FOREIGN KEY (ID_EQUIPE) REFERENCES GS_EQUIPE (ID_EQUIPE);
